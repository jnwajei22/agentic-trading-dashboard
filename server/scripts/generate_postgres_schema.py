"""Build a clean SQL snapshot from a brand-new local schema, never an existing DB.

This is a developer compatibility tool, not a SQLite data migration command.
"""
import re
import sqlite3
import tempfile
from pathlib import Path
from app.config.settings import settings
from app.storage.brokers import BrokerRepository
from app.storage.execution import ExecutionRepository
from app.storage.schedules import ScheduleRepository
from app.storage.runtime_settings import RuntimeSettingsRepository
from app.storage.user_experience import UserExperienceRepository
from app.storage.signal_intents import SignalIntentRepository
from app.storage.agent import AgentRepository
from app.services.market_data.candle_cache import DurableCandleCache
from app.services.tradelocker.rate_limiter import TradeLockerRequestLimiter


def generate():
    original = settings.storage_backend, settings.sqlite_path
    try:
        with tempfile.TemporaryDirectory() as tmp:
            settings.storage_backend, settings.sqlite_path = 'sqlite', tmp+'/schema.db'
            for cls in [BrokerRepository, ExecutionRepository, ScheduleRepository, RuntimeSettingsRepository,
                        UserExperienceRepository, SignalIntentRepository, AgentRepository, DurableCandleCache, TradeLockerRequestLimiter]: cls()
            with sqlite3.connect(settings.sqlite_path) as db:
                return snapshot(db)
    finally:
        settings.storage_backend, settings.sqlite_path = original


def snapshot(db):
    tables = dict(db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"))
    ordered = []
    while len(ordered) < len(tables):
        ready = [name for name in tables if name not in ordered and all(row[2] in ordered or row[2] == name for row in db.execute('PRAGMA foreign_key_list('+name+')'))]
        if not ready: raise RuntimeError('Foreign key cycle')
        ordered.extend(ready)
    sql = ['-- Fresh Supabase installation only. No SQLite rows are imported.', 'BEGIN;',
           'CREATE SCHEMA desk;', 'REVOKE ALL ON SCHEMA desk FROM PUBLIC;',
           'CREATE ROLE desk_runtime NOLOGIN;', 'SET LOCAL search_path TO desk, pg_catalog;']
    for name in ordered:
        statement = re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', tables[name], flags=re.I)
        statement = re.sub(r'\bINTEGER\b', 'BIGINT', statement, flags=re.I)
        statement = re.sub(r'\bBLOB\b', 'BYTEA', statement, flags=re.I)
        statement = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', statement, flags=re.I).replace(' COLLATE NOCASE', '')
        monetary = ('entry','stop_loss','take_profit','quantity','lot_size','estimated_risk','estimated_reward',
                    'estimated_margin','equity_high_watermark','risk_percent','risk_per_trade_percent',
                    'daily_loss_limit_percent','drawdown_cutoff_percent','minimum_reward_risk','reward_risk','minimum_confidence')
        for field in monetary:
            statement = re.sub(r'\b'+field+r' DOUBLE PRECISION', field+' NUMERIC(30,12)', statement)
        sql.append(statement+';')
    sql.extend(row[0]+';' for row in db.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"))
    sql.extend(['CREATE UNIQUE INDEX broker_account_alias_casefold ON broker_accounts(user_id,lower(account_alias));',
                'CREATE UNIQUE INDEX watchlist_name_casefold ON user_watchlists(user_sub,lower(name));'])
    for table in ordered:
        grouped = {}
        for row in db.execute('PRAGMA foreign_key_list('+table+')'): grouped.setdefault(row[0], []).append(row)
        for key, parts in grouped.items():
            columns = ','.join(part[3] for part in sorted(parts, key=lambda part:part[1]))
            sql.append(f'CREATE INDEX fk_{table}_{key} ON {table}({columns});')
    for table in ordered:
        columns = {row[1] for row in db.execute('PRAGMA table_info('+table+')')}
        owner = next((field for field in ('user_sub','user_id','auth0_sub') if field in columns), None)
        indexed = [tuple(row[2] for row in db.execute('PRAGMA index_info('+index[1]+')')) for index in db.execute('PRAGMA index_list('+table+')')]
        if owner and not any(fields and fields[0] == owner for fields in indexed):
            suffix = ',created_at' if 'created_at' in columns else ''
            sql.append(f'CREATE INDEX owner_{table} ON {table}({owner}{suffix});')
    for row in db.execute('SELECT public_id,name,version,description,config_json,created_at FROM strategy_templates'):
        # Seed only built-in templates with a stable timestamp. No account/user records.
        values = ["'"+str(value).replace("'", "''")+"'" for value in (*row[:5], '2026-01-01T00:00:00+00:00')]
        sql.append('INSERT INTO strategy_templates(public_id,name,version,description,config_json,created_at) VALUES('+','.join(values)+');')
    sql.extend(['CREATE TABLE schema_version(id BIGINT PRIMARY KEY CHECK(id=1), version BIGINT NOT NULL);', 'INSERT INTO schema_version VALUES(1,1);'])
    for table in ordered+['schema_version']:
        sql.extend([f'ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;',
                    f'CREATE POLICY desk_runtime_access ON {table} TO desk_runtime USING (true) WITH CHECK (true);'])
    sql.extend(['GRANT USAGE ON SCHEMA desk TO desk_runtime;',
                'GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA desk TO desk_runtime;',
                'REVOKE INSERT,UPDATE,DELETE ON schema_version FROM desk_runtime;',
                'GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA desk TO desk_runtime;', 'COMMIT;'])
    return '\n\n'.join(sql)+'\n'


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[2]/'supabase/schema.sql'
    target.parent.mkdir(exist_ok=True)
    target.write_text(generate())
    print('Generated fresh Postgres schema; no existing database was read.')
